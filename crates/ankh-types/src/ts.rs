/// Write the complete TypeScript declaration file to a path.
pub fn write_typescript_declarations(path: impl AsRef<Path>) -> io::Result<()> {
    fs::write(path, typescript_declarations())
}

/// Format a complete TypeScript declaration file.
pub fn format_typescript_declarations(input: &str, path: impl AsRef<Path>) -> io::Result<String> {
    let fmt_cfg = ConfigurationBuilder::new().deno().build();
    let path = path.as_ref();
    let options = FormatTextOptions {
        config: &fmt_cfg,
        path,
        text: input.to_owned(),
        extension: None,
        external_formatter: None,
    };
    format_text(options)
        .map_err(|err| io::Error::new(io::ErrorKind::InvalidData, err.to_string()))
        .map(|formatted| formatted.unwrap_or_else(|| input.to_owned()))
}

/// Append one exported declaration to the generated output.
fn push<T>(output: &mut String, cfg: &Config)
where
    T: TS + 'static,
{
    output.push_str("export ");
    output.push_str(T::decl(cfg).as_str());
    output.push_str("\n\n");
}

#[cfg(test)]
mod tests {
    //! Tests for generated TypeScript declarations.

    use std::{env, fs, path::PathBuf};

    use super::{
        TYPESCRIPT_DECLARATION_HEADER, TYPESCRIPT_DECLARATION_RELATIVE_PATH,
        typescript_declaration_body, typescript_declarations, write_typescript_declarations,
    };

    /// Resolve the generated declaration file from the crate directory.
    fn generated_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(TYPESCRIPT_DECLARATION_RELATIVE_PATH)
    }

    /// Proves generated declarations include representative shared DTOs.
    #[test]
    fn declarations_include_representative_shared_types() {
        let declarations = typescript_declarations();

        assert!(declarations.contains("export type UserInfo"));
        assert!(declarations.contains("export type DeviceSessionInfo"));
        assert!(declarations.contains("export type ListDeviceSessionsResponse"));
        assert!(!declarations.contains("PlayerSession"));
    }

    /// Proves declaration bodies can be embedded in product-owned generated files.
    #[test]
    fn declaration_body_omits_file_header() {
        let declarations = typescript_declaration_body();

        assert!(declarations.contains("export type UserInfo"));
        assert!(!declarations.starts_with(TYPESCRIPT_DECLARATION_HEADER));
    }

    /// Regenerates the checked-in declaration file when run explicitly.
    #[test]
    #[ignore = "regenerates checked-in TypeScript declarations"]
    fn export_typescript_declarations() {
        write_typescript_declarations(generated_path()).expect("write generated declarations");
    }

    /// Proves the checked-in `@ankh/types` declarations are fresh.
    #[test]
    fn generated_typescript_declarations_are_current() {
        let expected = typescript_declarations();
        let current =
            fs::read_to_string(generated_path()).expect("generated declarations are readable");

        assert_eq!(current, expected);
    }
}
