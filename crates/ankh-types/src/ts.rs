/// Relative path to the generated declaration file consumed by `@ankh/types`.
pub const TYPESCRIPT_DECLARATION_RELATIVE_PATH: &str = "frontend/packages/types/src/generated.d.ts";

/// Header used for generated TypeScript declaration files.
pub const TYPESCRIPT_DECLARATION_HEADER: &str =
    "// Generated by ankh-types. Do not edit by hand.\n\n";

/// Generate the complete TypeScript declaration file.
#[must_use]
pub fn typescript_declarations() -> String {
    let mut output = String::from(TYPESCRIPT_DECLARATION_HEADER);
    output.push_str(typescript_declaration_body().as_str());
    format_typescript_declarations(output.as_str(), TYPESCRIPT_DECLARATION_RELATIVE_PATH)
        .expect("format generated TypeScript declarations")
}

